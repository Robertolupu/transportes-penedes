document.documentElement.classList.add('js-enabled');

let currentLang = 'es';
let statsAnimated = false;

function applyTranslations() {
  const dictionary = i18n[currentLang];

  document.documentElement.lang = currentLang;
  document.title = dictionary.pageTitle;
  const metaDescription = document.querySelector('meta[name="description"]');
  if (metaDescription) metaDescription.setAttribute('content', dictionary.pageDescription);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (dictionary[key]) el.textContent = dictionary[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dictionary[key]) el.setAttribute('placeholder', dictionary[key]);
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const key = el.dataset.i18nAriaLabel;
    if (dictionary[key]) el.setAttribute('aria-label', dictionary[key]);
  });

  document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.langBtn === currentLang);
  });

  const whatsappFloat = document.getElementById('whatsappFloat');
  if (whatsappFloat) {
    const msg = encodeURIComponent(dictionary.whatsappMessage);
    whatsappFloat.setAttribute('href', `https://wa.me/34667685691?text=${msg}`);
  }

  if (statsAnimated) {
    document.querySelectorAll('[data-count]').forEach((el) => {
      const endValue = Number(el.dataset.count);
      el.textContent = endValue.toLocaleString(currentLang === 'es' ? 'es-ES' : 'en-US');
    });
  }

}

const revealEls = document.querySelectorAll('.reveal');
const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) entry.target.classList.add('visible');
    });
  },
  { threshold: 0.2 }
);
revealEls.forEach((el) => revealObserver.observe(el));

function animateCounter(el) {
  const endValue = Number(el.dataset.count);
  const duration = 1200;
  const start = performance.now();

  function step(now) {
    const progress = Math.min((now - start) / duration, 1);
    const value = Math.floor(progress * endValue);
    el.textContent = value.toLocaleString(currentLang === 'es' ? 'es-ES' : 'en-US');
    if (progress < 1) requestAnimationFrame(step);
  }

  requestAnimationFrame(step);
}

const statsSection = document.querySelector('.stats');
const countEls = document.querySelectorAll('[data-count]');
const yearsCounterEl = document.getElementById('yearsCounter');

if (yearsCounterEl) {
  const baseYear = Number(yearsCounterEl.dataset.baseYear || 2023);
  const currentYear = new Date().getFullYear();
  yearsCounterEl.dataset.count = String(Math.max(0, currentYear - baseYear));
}

const statsObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting && !statsAnimated) {
        countEls.forEach((el) => animateCounter(el));
        statsAnimated = true;
      }
    });
  },
  { threshold: 0.5 }
);
if (statsSection) statsObserver.observe(statsSection);

const menuToggle = document.querySelector('.menu-toggle');
const navLinks = document.querySelector('.nav-links');

if (menuToggle && navLinks) {
  menuToggle.addEventListener('click', () => {
    navLinks.classList.toggle('open');
  });

  navLinks.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => navLinks.classList.remove('open'));
  });
}

document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
  btn.addEventListener('click', () => {
    currentLang = btn.dataset.langBtn || 'es';
    localStorage.setItem('tp_lang', currentLang);
    applyTranslations();
  });
});

const form = document.getElementById('contactForm');
const formNote = document.getElementById('formNote');

if (form && formNote) {
  form.addEventListener('submit', async (event) => {
    event.preventDefault();
    const dictionary = i18n[currentLang];
    const submitButton = form.querySelector('button[type="submit"]');
    const formData = new FormData(form);
    const payload = {
      empresa: String(formData.get('empresa') || '').trim(),
      contacto: String(formData.get('contacto') || '').trim(),
      email: String(formData.get('email') || '').trim(),
      mensaje: String(formData.get('mensaje') || '').trim(),
    };

    formNote.textContent = dictionary.formSending;
    if (submitButton) submitButton.disabled = true;

    try {
      const response = await fetch('/api/contact', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      if (!response.ok) {
        throw new Error('Email API failed');
      }

      formNote.textContent = dictionary.formSuccess;
      form.reset();
    } catch (_error) {
      formNote.textContent = dictionary.formError;
    } finally {
      if (submitButton) submitButton.disabled = false;
    }
  });
}

const galleryTrack = document.getElementById('galleryTrack');
const galleryPrev = document.getElementById('galleryPrev');
const galleryNext = document.getElementById('galleryNext');
const galleryDots = document.getElementById('galleryDots');
const gallerySlides = galleryTrack ? Array.from(galleryTrack.querySelectorAll('.gallery-slide')) : [];
const lightbox = document.getElementById('lightbox');
const lightboxImage = document.getElementById('lightboxImage');
const lightboxClose = document.getElementById('lightboxClose');
let galleryIndex = 0;

function updateGallery() {
  if (!galleryTrack || gallerySlides.length === 0) return;
  galleryTrack.style.transform = `translateX(-${galleryIndex * 100}%)`;
  if (galleryDots) {
    galleryDots.querySelectorAll('button').forEach((dot, idx) => {
      dot.classList.toggle('active', idx === galleryIndex);
    });
  }
}

if (galleryPrev && galleryNext && gallerySlides.length > 0) {
  galleryPrev.addEventListener('click', () => {
    galleryIndex = (galleryIndex - 1 + gallerySlides.length) % gallerySlides.length;
    updateGallery();
  });

  galleryNext.addEventListener('click', () => {
    galleryIndex = (galleryIndex + 1) % gallerySlides.length;
    updateGallery();
  });

  if (galleryDots) {
    galleryDots.querySelectorAll('button').forEach((dot, idx) => {
      dot.addEventListener('click', () => {
        galleryIndex = idx;
        updateGallery();
      });
    });
  }

  setInterval(() => {
    galleryIndex = (galleryIndex + 1) % gallerySlides.length;
    updateGallery();
  }, 5500);

  updateGallery();
}

gallerySlides.forEach((slide) => {
  const img = slide.querySelector('img');
  if (!img) return;
  img.addEventListener('click', () => {
    if (!lightbox || !lightboxImage) return;
    lightboxImage.src = img.src;
    lightboxImage.alt = img.alt;
    lightbox.classList.add('open');
    lightbox.setAttribute('aria-hidden', 'false');
  });
});

if (lightbox && lightboxClose) {
  lightboxClose.addEventListener('click', () => {
    lightbox.classList.remove('open');
    lightbox.setAttribute('aria-hidden', 'true');
  });

  lightbox.addEventListener('click', (event) => {
    if (event.target === lightbox) {
      lightbox.classList.remove('open');
      lightbox.setAttribute('aria-hidden', 'true');
    }
  });
}

const yearEl = document.getElementById('year');
if (yearEl) yearEl.textContent = new Date().getFullYear();

const savedLang = localStorage.getItem('tp_lang');
if (savedLang === 'es' || savedLang === 'en') {
  currentLang = savedLang;
}

applyTranslations();
